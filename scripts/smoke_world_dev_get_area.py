failures = []


def check(label, cond, detail=None):
    print(("  ok   " if cond else "  FAIL ") + label
          + ("" if cond or detail is None else f"   -> {detail!r}"))
    if not cond:
        failures.append(label)


def num(v):
    s = f"{round(float(v), 2):.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def FMT(points):
    return "[" + ",".join(f"[{num(x)},{num(z)}]" for x, z in points) + "]"


run = wr.create_run("area", "m", "p", "u", 40, 300000)
ctx = wt.ToolCtx(run_id=run, turn=1)

R_POLY = ([[round(10 + 0.37 * i, 2), 46.13] for i in range(150)]
          + [[round(10 + 0.37 * (149 - j), 2), 54.13] for j in range(150)])
R_STROKE = [[round(10 + 0.37 * i, 2), 50.13] for i in range(150)]
check("R has 300 points", len(R_POLY) == 300)
R = terrain.save_area({"id": "ta_river", "kind": "water", "polygon": R_POLY,
                       "meta": {"stroke": {"points": R_STROKE, "width_m": 8}}})["id"]
SQ = []
for n, c in enumerate((20, 30, 40), 1):
    poly = [[c, c], [c + 4, c], [c + 4, c + 4], [c, c + 4]]
    SQ.append((terrain.save_area({"id": f"ta_sq{n}", "kind": "grass",
                                  "polygon": poly})["id"], c))
H_POLY = ([[round(10 + 0.37 * i, 2), 80.5] for i in range(150)]
          + [[round(10 + 0.37 * (149 - j), 2), 85.5] for j in range(150)])
H = save_height_area({"id": "ha_hill", "polygon": H_POLY, "height_m": 5,
                      "falloff_m": 30, "meta": {"label": "Demo Hill"}})["id"]

# (a)
res = wt.run_tool(ctx, "map_region", {"min_x": 0, "min_z": 0, "max_x": 100,
                                       "max_z": 100, "polygons": True})
check("(a) ok", res.ok, res.line[:300])
lines = res.line.split("\n")
r_ptr = (f'terrain {R} water bbox (10,46.13)-(65.13,54.13) z_order 0 '
         f'polygon: 300 points — get_area{{"id": "{R}"}}')
check("(a) R pointer line", r_ptr in lines, lines[:2])
for sid, c in SQ:
    want = (f"terrain {sid} grass bbox ({c},{c})-({c + 4},{c + 4}) z_order 0 polygon "
            f"[[{c},{c}],[{c + 4},{c}],[{c + 4},{c + 4}],[{c},{c + 4}]]")
    check(f"(a) {sid} listed with polygon", want in lines, lines)
    check(f"(a) {sid} after R", r_ptr in lines and want in lines
          and lines.index(want) > lines.index(r_ptr))
h_ptr = (f'height {H} "Demo Hill" 5 m falloff 30 m bbox (10,80.5)-(65.13,85.5) '
         f'polygon: 300 points — get_area{{"id": "{H}"}}')
check("(a) H pointer line", h_ptr in lines, lines)
check("(a) nothing dropped", not any(l.startswith("…") for l in lines), lines[-1])
res = wt.run_tool(ctx, "map_region", {"min_x": 0, "min_z": 0, "max_x": 100,
                                       "max_z": 100})
check("(a) no polygons without the flag", "polygon" not in res.line, res.line)

# (b)
res = wt.run_tool(ctx, "get_area", {"id": R})
check("(b) ok", res.ok, res.line[:300])
out = res.line.split("\n")
check("(b) head line", out[0] == f"terrain {R} water z_order 0", out[0])
check("(b) full stroke first", len(out) > 1
      and out[1] == "stroke: width_m 8 points " + FMT(R_STROKE),
      out[1][:120] if len(out) > 1 else None)
check("(b) full polygon", len(out) > 2 and out[2] == "polygon (300 points): " + FMT(R_POLY),
      out[2][:120] if len(out) > 2 else None)
check("(b) three lines", len(out) == 3, len(out))
check("(b) no cut", "[cut" not in res.line)
check("(b) journalled as read", wr.steps(run)[-1]["kind"] == "read", wr.steps(run)[-1]["kind"])

# (c)
res = wt.run_tool(ctx, "get_area", {"id": H})
out = res.line.split("\n")
check("(c) height head", out[0] == f'height {H} "Demo Hill" height_m 5 falloff_m 30', out[0])
check("(c) height polygon", len(out) > 1
      and out[1] == "polygon (300 points): " + FMT(H_POLY))

# (d)
res = wt.run_tool(ctx, "get_area", {"id": "ta_nosuch"})
check("(d) refused", not res.ok and "no terrain or height area" in res.line, res.line)
res = wt.run_tool(ctx, "get_area", {})
check("(d) id required", not res.ok, res.line)

# (e)
check("(e) budget constant", getattr(wt, "MAX_AREA_CHARS", None) == 12000)
L_POLY = [[round(1000.11 + i, 2), 2000.22] for i in range(2000)]
L = terrain.save_area({"id": "ta_long", "kind": "grass", "polygon": L_POLY})["id"]
full = f"terrain {L} grass z_order 0\npolygon (2000 points): " + FMT(L_POLY)
check("(e) fixture longer than the budget", len(full) > 12000, len(full))
res = wt.run_tool(ctx, "get_area", {"id": L})
want = ("terrain ta_long grass z_order 0\npolygon (2000 points): ["
        + ",".join(f"[{num(x)},{num(z)}]" for x, z in L_POLY[:659]) + ",…]"
        + "\n[cut — polygon: 659 of 2000 points shown]")
check("(e) cut on point 659", res.line == want, res.line[-120:])
check("(e) polygon line 11888 chars", len(res.line.split("\n")[1]) == 11888,
      len(res.line.split("\n")[1]))
check("(e) within the budget", len(res.line) <= 12000, len(res.line))

# (f)
M_POLY = ([[round(210.13 + 1.01 * i, 2), 220.17] for i in range(40)]
          + [[round(210.13 + 1.01 * (39 - j), 2), 230.17] for j in range(40)])
terrain.save_area({"id": "ta_mid", "kind": "grass", "polygon": M_POLY})
check("(f) M outline text 1273 chars", len(wt._fmt_points(M_POLY)) == 1273,
      len(wt._fmt_points(M_POLY)))
check("(f) ceiling constant", getattr(wt, "MAX_REGION_POLY_CHARS", None) == 400)
SQ5 = []
for n, c in enumerate((260, 265, 270, 275, 280), 1):
    poly = [[c, c], [c + 4, c], [c + 4, c + 4], [c, c + 4]]
    SQ5.append((terrain.save_area({"id": f"ta_m{n}", "kind": "grass",
                                   "polygon": poly})["id"], c))
res = wt.run_tool(ctx, "map_region", {"min_x": 200, "min_z": 200, "max_x": 300,
                                       "max_z": 300, "polygons": True})
lines = res.line.split("\n")
m_ptr = ('terrain ta_mid grass bbox (210.13,220.17)-(249.52,230.17) z_order 0 '
         'polygon: 80 points — get_area{"id": "ta_mid"}')
check("(f) M pointer line", m_ptr in lines, lines[:2])
for sid, c in SQ5:
    want = (f"terrain {sid} grass bbox ({c},{c})-({c + 4},{c + 4}) z_order 0 polygon "
            f"[[{c},{c}],[{c + 4},{c}],[{c + 4},{c + 4}],[{c},{c + 4}]]")
    check(f"(f) {sid} listed with polygon", want in lines, lines)
check("(f) nothing dropped", not any(l.startswith("…") for l in lines), lines[-1])
check("(f) six lines", len(lines) == 6, len(lines))

# (g)
G_STROKE = [[round(100.11 + i, 2), 500.22] for i in range(400)]
G_POLY = ([[round(100.11 + i, 2), 496.22] for i in range(400)]
          + [[round(100.11 + (399 - j), 2), 504.22] for j in range(400)])
terrain.save_area({"id": "ta_road", "kind": "water", "polygon": G_POLY,
                   "meta": {"stroke": {"points": G_STROKE, "width_m": 8}}})
res = wt.run_tool(ctx, "get_area", {"id": "ta_road"})
out = res.line.split("\n")
check("(g) head", out[0] == "terrain ta_road water z_order 0", out[0])
check("(g) whole stroke line", len(out) > 1
      and out[1] == "stroke: width_m 8 points " + FMT(G_STROKE)
      and len(out[1]) == 6426, out[1][:80] if len(out) > 1 else None)
check("(g) polygon cut on point 339", len(out) > 2
      and out[2] == "polygon (800 points): [" + ",".join(
          f"[{num(x)},{num(z)}]" for x, z in G_POLY[:339]) + ",…]"
      and len(out[2]) == 5449, out[2][-60:] if len(out) > 2 else None)
check("(g) cut line", len(out) == 4 and out[3] == "[cut — polygon: 339 of 800 points shown]",
      out[3:] if len(out) > 3 else None)
check("(g) within the budget", len(res.line) <= 12000, len(res.line))

# (h)
terrain.save_area({"id": "ta_brook", "kind": "water",
                   "polygon": [[5, 3], [25, 3], [25, 10], [5, 10]],
                   "meta": {"stroke": {"points": [[5, 5], [15, 5], [25, 8]],
                                       "width_m": 3, "style": "wavy",
                                       "spacing_m": 6, "amplitude_m": 1.5}}})
res = wt.run_tool(ctx, "get_area", {"id": "ta_brook"})
out = res.line.split("\n")
check("(h) stroke with optional keys", len(out) > 1 and out[1] ==
      "stroke: width_m 3 style wavy spacing_m 6 amplitude_m 1.5 points "
      "[[5,5],[15,5],[25,8]]", out[1:2])
check("(h) polygon", len(out) > 2 and out[2] == "polygon (4 points): [[5,3],[25,3],[25,10],[5,10]]",
      out[2:3])
check("(h) no cut line", len(out) == 3, out)

