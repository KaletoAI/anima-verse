#!/usr/bin/env python3
"""Smoke: World Dev free mode — full area geometry, get_area (gap 19, part 2).

Plan docs/superpowers/plans/2026-11-25-world-dev-free-p1-characters.md, Task 11
(decision D11). A temp world (paths.init BEFORE any world-DB import), an EMPTY
ANIMATION_CLIPS_DIR; no server, no LLM. Every call goes through
``world_dev_tools.run_tool`` exactly as the agent loop calls it.

Usage:
    ./.venv/bin/python scripts/smoke_world_dev_get_area.py

WHAT IS CHECKED, and where every expected value comes from
----------------------------------------------------------

Number format of the full geometry (get_area): every coordinate is the stored
value (app/models/terrain._sanitize_points rounds to 2 decimals) written with
2 decimals and trailing zeros / a trailing "." dropped — 10.0 -> "10",
10.37 -> "10.37", 10.7 -> "10.7". A point list is "[[x,z],[x,z],...]" with no
spaces (valid JSON). FMT below is that rule; the coordinates are generated by
the formulas below, not read back from the tool.

Fixtures (all in the box (0,0)-(100,100)), created in this order with
z_order 0, so terrain.list_areas (z_order, then paint order) lists them
R, S1, S2, S3:

  R  kind "water", polygon of 300 points: for i = 0..149 the upper edge
     [10 + 0.37*i, 46.13], then for j = 0..149 the lower edge back
     [10 + 0.37*(149-j), 54.13] (rounded to 2 decimals). meta.stroke =
     {points: [10 + 0.37*i, 50.13] for i = 0..149, width_m: 8}.
     bbox x 10 … 10 + 0.37*149 = 65.13, z 46.13 … 54.13.
  S1 kind "grass", square [[20,20],[24,20],[24,24],[20,24]]
  S2 kind "grass", square [[30,30],[34,30],[34,34],[30,34]]
  S3 kind "grass", square [[40,40],[44,40],[44,44],[40,44]]
  H  height area, 300 points: [10 + 0.37*i, 80.5] then [10 + 0.37*(149-j), 85.5],
     height_m 5, falloff_m 30, label "Demo Hill" -> bbox (10,80.5)-(65.13,85.5).

  (a) map_region{0,0,100,100, polygons: true} — the read cap is
      MAX_RESULT_CHARS = 1500 (with _cap_lines' 60-character reserve). R's
      polygon alone is 300 points of at least "[10,46.13]," = 11 characters,
      more than 1500, so R's line is the pointer
      'terrain <R> water bbox (10,46.13)-(65.13,54.13) z_order 0 polygon: 300
      points — get_area{"id": "<R>"}'; S1–S3 are still listed AFTER it with
      their polygons ('terrain <S1> grass bbox (20,20)-(24,24) z_order 0
      polygon [[20,20],[24,20],[24,24],[20,24]]', likewise S2/S3); the height
      area H gets its pointer too ('height <H> "Demo Hill" 5 m falloff 30 m
      bbox (10,80.5)-(65.13,85.5) polygon: 300 points — get_area{"id":
      "<H>"}'); no "… N more" line (6 short lines are far below 1500).
      Without polygons the lines carry no polygon at all (unchanged).
  (b) get_area{R}: line 1 'terrain <R> water z_order 0', line 2 (the stroke
      is the recipe, so it comes BEFORE the derived polygon)
      'stroke: width_m 8 points ' + FMT(stroke points) — all 150 points,
      line 3 'polygon (300 points): ' + FMT(R polygon) — all 300 points.
      Journalled as kind "read".
  (c) get_area{H}: 'height <H> "Demo Hill" height_m 5 falloff_m 30' then
      'polygon (300 points): ' + FMT(H polygon).
  (d) unknown id "ta_nosuch" -> refused: ok False, "no terrain or height area".
  (e) own budget MAX_AREA_CHARS = 12000, of which 80 characters are kept for
      the cut line; every list is cut on a WHOLE point and closed by ",…]".
      A terrain area L of 2000 points [1000.11 + i, 2000.22] (i = 0..1999):
      every point is "[dddd.11,2000.22]" = 17 characters. Head
      'terrain ta_long grass z_order 0' = 31 characters, so the polygon line
      may take 12000 - 80 - 31 - 1 (newline) = 11888 characters. Prefix
      'polygon (2000 points): ' = 23; n points take 23 + 1 ("[") + 17n +
      (n - 1) commas + 3 (",…]") = 26 + 18n <= 11888 -> n = 659 (exactly
      11888). Result: head, 'polygon (2000 points): [' + the first 659
      points joined by "," + ',…]', then '[cut — polygon: 659 of 2000 points
      shown]'. No coordinate is split.
  (f) mid-size outline (D11 must not depend on the remaining budget): box
      (200,200)-(300,300) holds M, kind "grass", 80 points: for i = 0..39
      [210.13 + 1.01*i, 220.17], then for j = 0..39 [210.13 + 1.01*(39-j),
      230.17] (bbox x 210.13 … 249.52, z 220.17 … 230.17), and after it five
      squares S1..S5 [[c,c],[c+4,c],[c+4,c+4],[c,c+4]] for c = 260, 265, 270,
      275, 280. An M point is "[ddd.dd,2d0.17]" = 15 characters, except where
      the x hundredths digit is 0 and is dropped (13 + i ≡ 0 mod 10: i = 7,
      17, 27, 37 on each edge -> 8 points of 14), so its outline is
      80*15 - 8 + 79 + 2 = 1273 characters: below the 1500 read
      budget (the old code printed it and dropped 4 squares) but above the
      own ceiling MAX_REGION_POLY_CHARS = 400 -> M's line is the pointer
      'terrain ta_mid grass bbox (210.13,220.17)-(249.52,230.17) z_order 0
      polygon: 80 points — get_area{"id": "ta_mid"}' and all five squares
      follow with their polygons; no "… N more" line.
  (g) long stroke (the recipe must survive the cut): area ta_road, kind
      "water", stroke {points [100.11 + i, 500.22] for i = 0..399, width_m 8},
      polygon of 800 points [100.11 + i, 496.22] for i = 0..399 then
      [100.11 + (399-j), 504.22] for j = 0..399. Each point is
      "[ddd.11,50d.22]" = 15 characters. Head 'terrain ta_road water z_order
      0' = 31, so 11889 characters are left (12000 - 80 - 31). Stroke line
      'stroke: width_m 8 points ' (25) + 400*15 + 399 + 2 = 6426 <= 11888 ->
      WHOLE. Left for the polygon: 11889 - 6427 = 5462, line budget 5461.
      Prefix 'polygon (800 points): ' = 22; n points take 22 + 1 + 15n +
      (n - 1) + 3 = 25 + 16n <= 5461 -> n = 339 (line length 5449). Result:
      head, the whole stroke line, 'polygon (800 points): [' + the first 339
      polygon points + ',…]', then '[cut — polygon: 339 of 800 points shown]'.
  (h) optional stroke keys: area ta_brook, kind "water", stroke {points
      [[5,5],[15,5],[25,8]], width_m 3, style "wavy", spacing_m 6,
      amplitude_m 1.5} (all inside terrain's clamps 2..100 / 0.5..30, so
      stored as given), polygon [[5,3],[25,3],[25,10],[5,10]] -> line 2 is
      'stroke: width_m 3 style wavy spacing_m 6 amplitude_m 1.5 points
      [[5,5],[15,5],[25,8]]', line 3 'polygon (4 points):
      [[5,3],[25,3],[25,10],[5,10]]', no cut line.
  (i) a label with double quotes is printed with single ones: label
      'a "q" line' on S1 -> get_area head 'terrain ta_sq1 grass "a 'q' line"
      z_order 0'.
  (j) a stroke that fills the budget must leave room for the polygon line:
      area ta_fill, kind "water", label "L" * 200 (shortened by _short to
      79 "L" + "…" = 80 characters), stroke {points [1000.11 + i, 2000.22]
      for i = 0..1023 (MAX_STROKE_POINTS), width_m 8}, polygon of 2048
      points [3000.11 + i, 4000.22] (i = 0..2047). Head
      'terrain ta_fill water "' + 80 + '" z_order 0' = 22 + 1 + 80 + 1 + 10
      = 114, so 12000 - 80 - 114 = 11806 are left. The shortest polygon
      line 'polygon (2048 points): […]' (26) plus its newline (27) is
      reserved, so the stroke line budget is 11806 - 1 - 27 = 11778. Every
      stroke point is "[dddd.11,2000.22]" = 17 characters; prefix
      'stroke: width_m 8 points ' = 25; n points take 25 + 1 + 17n + (n - 1)
      + 3 = 28 + 18n <= 11778 -> n = 652 (line 11764). Left for the polygon
      11806 - 11765 = 41, line budget 40: one point would take 23 + 1 + 17
      + 3 = 44 > 40, so the line is 'polygon (2048 points): […]'. Cut line
      '[cut — stroke: 652 of 1024 points shown; polygon: 0 of 2048 points
      shown]' = 7 + 32 + 2 + 31 + 1 = 73. Total 114 + 1 + 11764 + 1 + 26 + 1
      + 73 = 11980 <= 12000. (The code before this fix budgeted the stroke
      without the reserve: 654 points, line 11800, total 12016.)
  (k) map_region outlines keep every stored decimal: ta_far, kind "grass",
      polygon [[12345.67,54321.12],[12349.67,54321.12],[12349.67,54325.12]]
      in box (12000,54000)-(13000,55000) -> the line ends
      'polygon [[12345.67,54321.12],[12349.67,54321.12],[12349.67,54325.12]]'
      (":g" would print 12345.7,54321.1); the bbox stays on :g:
      'bbox (12345.7,54321.1)-(12349.7,54325.1)'.
  (l) rows along a stroke survive an update: ta_lamps, kind "water", stroke
      {points [[300,300],[340,300]], width_m 6, along [{spacing_m 25,
      offset_m 4}]} (sanitised to exactly those two keys), polygon
      [[300,297],[340,297],[340,303],[300,303]]. get_area line 2 is
      'stroke: width_m 6 along: 1 rows (kept on update) points
      [[300,300],[340,300]]'. update_terrain_area{id, stroke {points
      [[300,310],[340,310]], width_m 6}} (turn 2; every earlier call was
      turn 1 and a read) -> stored meta.stroke ==
      {points [[300,310],[340,310]], width_m 6, along [{spacing_m 25,
      offset_m 4}]}. undo(run, turn=2) restores the whole row: meta.stroke points
      [[300,300],[340,300]] again, along unchanged.
"""
